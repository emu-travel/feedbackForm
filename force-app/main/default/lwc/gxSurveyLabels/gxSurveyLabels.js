/**
 * Fills {0}, {1}, ... in a label: formatLabel("Schritt {0} von {1}", 2, 5).
 * A placeholder with nothing to fill it is left as it is.
 */
export function formatLabel(label, ...args) {
  return String(label === undefined || label === null ? "" : label).replace(
    /\{(\d+)\}/g,
    (match, index) => {
      const arg = args[index];
      return arg === undefined || arg === null ? match : String(arg);
    }
  );
}
